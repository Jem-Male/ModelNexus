# 1. Подготовленный массив ответов (текст или JSON-строки для форм)
PREPARED_RESPONSES = [
    lesson_plan,
    *[json.dumps(lesson, ensure_ascii=False) for lesson in lessons],
    quizs,
    task
]

# Бесконечный итератор, который выдает элементы по очереди и начинает заново, когда они кончатся
response_iterator = cycle(PREPARED_RESPONSES)


# Схемы входящего запроса (совместимы с OpenAI SDK)
class Message(BaseModel):
    role: str
    content: Any


class ChatCompletionRequest(BaseModel):
    model: str
    messages: List[Message]
    temperature: Optional[float] = 1.0
    max_tokens: Optional[int] = None


# 2. Эндпоинт, куда стучится cl.chat.completions.create()
@app.post("/v1/chat/completions")
@app.post("/chat/completions")
async def create_chat_completion(request: ChatCompletionRequest):
    # Берем следующий элемент из подготовленного массива
    next_answer = next(response_iterator)

    # Формируем ответ в точном формате OpenAI ChatCompletion
    return {
        "id": f"chatcmpl-{uuid.uuid4().hex}",
        "object": "chat.completion",
        "created": int(time.time()),
        "model": request.model,
        "choices": [
            {
                "index": 0,
                "message": {
                    "role": "assistant",
                    "content": next_answer
                },
                "logprobs": None,
                "finish_reason": "stop"
            }
        ],
        "usage": {
            "prompt_tokens": 0,
            "completion_tokens": 0,
            "total_tokens": 0
        }
    }

# Эндпоинт для сброса очереди в начало (удобно при тестировании)
@app.post("/reset")
async def reset_queue():
    global response_iterator
    response_iterator = cycle(PREPARED_RESPONSES)
    return {"status": "Очередь ответов сброшена в начало"}
